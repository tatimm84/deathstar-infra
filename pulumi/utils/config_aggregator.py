"""
Configuration Aggregator Utility.

This module provides helper functions to aggregate and normalize configuration
payloads generated dynamically by different modules
"""

from collections import defaultdict
from typing import Any


def merge_module_configs(modules: list[dict[str, Any]]) -> dict[str, list[Any]]:
    """
    Merge configuration dictionaries produced by multiple modules into a
    single unified structure.

    Parameters
    ----------
    modules : list[dict[str, Any]]
        List of configuration dictionaries generated by modules.

    Returns
    -------
    dict[str, list[Any]]
        A merged dictionary where:
        - Each key aggregates values across all modules
        - Lists are concatenated preserving order of modules and items
    """
    merged: dict[str, list[Any]] = defaultdict(list)

    for module in modules:
        for key, value in module.items():
            if value:
                merged[key].extend(value)

    return dict(merged)


def merge_module_configs_dedup(
    modules: list[dict[str, Any]],
) -> dict[str, list[Any]]:
    """
    Merge module configurations with deduplication based on the 'source' field.

    This function extends `merge_module_configs` by ensuring that duplicate
    resource definitions are not included multiple times.

    Deduplication strategy:
        - Uses the "source" attribute as a unique identifier
        - Only the first occurrence is preserved

    Parameters
    ----------
    modules : list[dict[str, Any]]
        List of module configuration dictionaries.

    Returns
    -------
    dict[str, list[Any]]
        Aggregated configuration dictionary without duplicate entries.
    """
    merged: dict[str, list[Any]] = defaultdict(list)
    seen_ids: dict[str, set] = defaultdict(set)

    for module in modules:
        for key, value in module.items():
            for item in value or []:
                unique_id = item.get("source")

                # Include if no identifier OR not seen before
                if not unique_id or unique_id not in seen_ids[key]:
                    merged[key].append(item)

                    if unique_id:
                        seen_ids[key].add(unique_id)

    return dict(merged)
